// Bundles the Evaluation Lab engine (src/lib/evaluationLab) for the doctor-evaluation-v6 Edge
// Function, so the doctor dashboard and /evaluation-lab score with the same code.
// Run after any change to the engine:  node scripts/build-doctor-evaluation-edge.mjs
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');

await build({
  stdin: {
    contents: [
      "export { computeCycleScores, serverCycle, LAB_CURRENT_VERSION } from '@/lib/evaluationLab/server/cycleScores';",
      "export { setEvidenceClient } from '@/lib/evaluationLab/server/supabaseShim';",
    ].join('\n'),
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: path.join(root, 'supabase/functions/doctor-evaluation-v6/engine.js'),
  banner: { js: '// @ts-nocheck\n// GENERATED by scripts/build-doctor-evaluation-edge.mjs from src/lib/evaluationLab. Do not edit.' },
  legalComments: 'none',
  minify: true,
  plugins: [{
    name: 'dawaa-alias',
    setup(b) {
      // The engine's only I/O goes through the client the function hands in.
      b.onResolve({ filter: /^@\/lib\/supabase$/ }, () => ({ path: path.join(src, 'lib/evaluationLab/server/supabaseShim.ts') }));
      b.onResolve({ filter: /^@\// }, async (args) => {
        const result = await b.resolve(`./${args.path.slice(2)}`, { resolveDir: src, kind: args.kind });
        return result.errors.length ? { errors: result.errors } : { path: result.path };
      });
    },
  }],
  logLevel: 'info',
});
