-- تصحيح لكشوف الحوافز اللي اتسجلت في 20260829180000_settle_july_august_incentive_cycle.sql:
-- تلك الكشوف اتحسبت بفورمولا "تراكم من صفر" (min(نقاط, تارجت) × سعر)،
-- لكن الفورمولا الحقيقية المعتمدة في dawaa_staff_points_truth_v2 هي
-- "رصيد ابتدائي = التارجت، ثم +مكافآت -خصومات، بحد أقصى 100% من السقف".
-- بما إن كل العشرين موظف كان صافي نقاطهم صفر أو موجب لهذه الدورة (مفيش
-- خصومات تجاوزت مكافآتهم)، القيمة الصحيحة للجميع هي السقف الكامل.
--
-- طُبّق هذا التصحيح مباشرة على قاعدة الإنتاج بتاريخ 2026-08-29 فور اكتشاف
-- الفرق بين الفورمولتين أثناء اختبار إصلاح دالة points-truth. هذا الملف
-- يوثّق نفس التصحيح في المستودع حسب docs/ARCHITECTURE_TARGET.md البند 11.

update public.employee_monthly_statements
set incentive_amount = case
    when staff_name in ('د/ حسن','د اسلام فاروق','د/ بسنت','د/ ندي','د/ سارة','د/ وليد','د/ يوسف') then 1500
    when staff_name in ('د احمد حافظ','د احمد وليد','د رضا','د محمد شبل','د/ عمر','د/ مي') then 750
    when staff_name in ('د/ محمد علي','د/ شيماء','د دنيا','د هدي ') then 1000
    when staff_name in ('هبه حماده','هاجر','د/ محمد خالد') then 700
  end,
  net_salary = case
    when staff_name in ('د/ حسن','د اسلام فاروق','د/ بسنت','د/ ندي','د/ سارة','د/ وليد','د/ يوسف') then 1500
    when staff_name in ('د احمد حافظ','د احمد وليد','د رضا','د محمد شبل','د/ عمر','د/ مي') then 750
    when staff_name in ('د/ محمد علي','د/ شيماء','د دنيا','د هدي ') then 1000
    when staff_name in ('هبه حماده','هاجر','د/ محمد خالد') then 700
  end
where cycle_start = '2026-07-26' and cycle_end = '2026-08-25';
