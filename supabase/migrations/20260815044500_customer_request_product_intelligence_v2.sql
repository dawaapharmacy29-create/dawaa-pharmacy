-- Movement-aware, dosage-safe product matching for Base44 customer requests.

create table if not exists public.product_movement_evidence (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products(id) on delete cascade,
  product_code text not null,
  branch text,
  movement_date date not null,
  quantity numeric not null default 0,
  movement_type text not null default 'sale',
  source text not null default 'manual_import',
  source_ref text,
  created_at timestamptz not null default now()
);

create index if not exists idx_product_movement_evidence_product_date on public.product_movement_evidence(product_id, movement_date desc);
create index if not exists idx_product_movement_evidence_code_date on public.product_movement_evidence(product_code, movement_date desc);

create or replace function public.customer_request_smart_product_text_v2(p_value text)
returns text
language plpgsql
immutable
set search_path=public,pg_catalog
as $$
declare v text := lower(coalesce(p_value,''));
begin
  v := translate(v, 'أإآىةؤئ', 'ااايهوي');
  v := regexp_replace(v, '[\u064B-\u065F\u0670]', '', 'g');
  v := replace(v, 'milligrams', ' mg '); v := replace(v, 'milligram', ' mg ');
  v := replace(v, 'مجم', ' mg '); v := replace(v, 'مغ', ' mg ');
  v := replace(v, 'micrograms', ' mcg '); v := replace(v, 'microgram', ' mcg ');
  v := replace(v, 'milliliters', ' ml '); v := replace(v, 'milliliter', ' ml ');
  v := replace(v, 'مللي', ' ml '); v := replace(v, 'مللى', ' ml ');
  v := replace(v, 'tablets', ' tab '); v := replace(v, 'tablet', ' tab ');
  v := replace(v, 'اقراص', ' tab '); v := replace(v, 'قرص', ' tab ');
  v := replace(v, 'capsules', ' cap '); v := replace(v, 'capsule', ' cap ');
  v := replace(v, 'كبسولات', ' cap '); v := replace(v, 'كبسوله', ' cap ');
  v := replace(v, 'ampoules', ' amp '); v := replace(v, 'ampoule', ' amp ');
  v := replace(v, 'امبولات', ' amp '); v := replace(v, 'امبول', ' amp ');
  v := regexp_replace(v, '([0-9])([a-z\u0600-\u06ff])', '\1 \2', 'g');
  v := regexp_replace(v, '([a-z\u0600-\u06ff])([0-9])', '\1 \2', 'g');
  v := regexp_replace(v, '[^a-z0-9\u0600-\u06ff.%]+', ' ', 'g');
  v := regexp_replace(v, '\s+', ' ', 'g');
  return nullif(trim(v),'');
end;
$$;

create or replace function public.customer_request_strength_tokens_v2(p_value text)
returns text[]
language sql
immutable
set search_path=public,pg_catalog
as $$
  with x as (select public.customer_request_smart_product_text_v2(p_value) v),
  m as (
    select lower(replace(r[1],' ','')) token
    from x, regexp_matches(coalesce(v,''), '([0-9]+(?:[.]?[0-9]+)?\s*(?:mg|mcg|g|ml|iu|%))', 'g') r
  )
  select coalesce(array_agg(distinct token order by token), array[]::text[]) from m;
$$;

create or replace function public.customer_request_form_v2(p_value text)
returns text
language sql
immutable
set search_path=public,pg_catalog
as $$
  select case
    when coalesce(public.customer_request_smart_product_text_v2(p_value),'') ~ '(^| )(amp|امبوله)( |$)' then 'amp'
    when coalesce(public.customer_request_smart_product_text_v2(p_value),'') ~ '(^| )(tab)( |$)' then 'tab'
    when coalesce(public.customer_request_smart_product_text_v2(p_value),'') ~ '(^| )(cap)( |$)' then 'cap'
    when lower(coalesce(p_value,'')) ~ '(cream|كريم)' then 'cream'
    when lower(coalesce(p_value,'')) ~ '(gel|جل)' then 'gel'
    when lower(coalesce(p_value,'')) ~ '(syrup|syp|شراب)' then 'syrup'
    when lower(coalesce(p_value,'')) ~ '(spray|بخاخ|سبراي)' then 'spray'
    when lower(coalesce(p_value,'')) ~ '(drop|drops|قطره|قطرة)' then 'drop'
    when lower(coalesce(p_value,'')) ~ '(supp|suppos|لبوس|تحميل)' then 'supp'
    when lower(coalesce(p_value,'')) ~ '(sachet|sachets|كيس|اكياس)' then 'sachet'
    when lower(coalesce(p_value,'')) ~ '(lotion|لوشن)' then 'lotion'
    when lower(coalesce(p_value,'')) ~ '(ointment|oint|مرهم)' then 'ointment'
    else null end;
$$;

